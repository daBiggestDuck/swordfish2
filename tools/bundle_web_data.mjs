import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const mapsRoot = resolve(repoRoot, 'data', 'maps');
const rawRoot = resolve(mapsRoot, 'raw');
const outFile = resolve(repoRoot, 'web', 'map_data_bundle.js');

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, 'utf8'));
}

const bundle = {
  main: readJson(resolve(mapsRoot, 'lunar_map_data.json')),
  quickmap: readJson(resolve(rawRoot, 'quickmap_lroc_stack3314.json')),
  trekSites: readJson(resolve(rawRoot, 'trek_clps_sites.json')),
  trekPsr: readJson(resolve(rawRoot, 'trek_south_pole_psr.json')),
  lola: readJson(resolve(rawRoot, 'trek_lola_terrain_profiles.json')),
  horizons: readJson(resolve(rawRoot, 'horizons_lunar_ephemeris.json')),
};

const serialized = JSON.stringify(bundle)
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029');

const banner = [
  '// Auto-generated by tools/bundle_web_data.mjs — do not edit by hand.',
  '// Enables the Lunar Map UI to run purely statically (e.g. VS Code Live Server)',
  '// when /api/map/* backend routes are unavailable.',
  `export const BUNDLED_MAP_DATA = ${serialized};`,
  '',
].join('\n');

writeFileSync(outFile, banner, 'utf8');
console.log(`Wrote ${outFile} (${Buffer.byteLength(banner, 'utf8')} bytes)`);
